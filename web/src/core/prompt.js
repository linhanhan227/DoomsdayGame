/**
 * 选项文案「去剧透」清理（引擎侧兜底）。
 * ------------------------------------------------------------------
 * 选项只应描述"做什么"，不应提前兑现"会怎样"。模型偶尔仍会写出
 * 「安全地爬上去」「成功地撬开门」这类把结果写在题面上的选项——那会让选择失去意义。
 * 这里只做**保守的**清理：命中固定的结果/优劣副词就把它删掉，其余一字不动；
 * 清理后若几乎不剩内容（< 2 字）则放弃清理，避免把选项改坏。
 * ⚠ 这是兜底，不是主手段——主手段是【选项设计 · 不给标准答案】那套约束。
 */
const SPOILER_ADVERBS = [
  '安全地', '成功地', '顺利地', '轻松地', '侥幸地', '稳妥地', '有效地', '安然地',
  '明智地', '贸然地', '愚蠢地', '冒险地', '危险地', '果断地', '大胆地', '谨慎地',
]

/** 去掉选项文案里暴露结果 / 优劣的副词（命中才改，改坏则原样返回） */
export function polishChoiceText(raw) {
  const src = String(raw || '').trim()
  if (!src) return src
  let t = src
  for (const w of SPOILER_ADVERBS) {
    while (t.includes(w)) t = t.replace(w, '')
  }
  // 副词被摘掉后可能留下悬空的标点
  t = t
    .replace(/^[，、,。；;：:\s]+/, '')
    .replace(/[，、,]\s*$/, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
  return t.length >= 2 ? t : src
}

/**
 * 任务焦点：这一回合的事件应当围绕哪条任务线生成。
 * ------------------------------------------------------------------
 * 规则（与【任务链】设定严格对应）：
 *   · 默认焦点是**主线**；
 *   · 玩家上一步选择了服务于某条支线的选项时，焦点切到那条支线；
 *   · 该支线一旦了结（done / failed / abandoned）或不再存在，焦点自动回归主线。
 * 返回 { type:'main'|'side', title, stage?/note? }
 */
export function questFocusOf(state) {
  const active = (state?.sideQuests || []).filter((q) => q.status === 'active')
  const f = state?.questFocus
  if (f && f.type === 'side') {
    const q = active.find((x) => x.title === f.title)
    if (q) return { type: 'side', title: q.title, note: q.note || '' }
  }
  const mq = state?.mainQuest
  return { type: 'main', title: mq?.title || '活下去', stage: mq?.stage || '' }
}

/** 把任务焦点渲染成一行提示（供事件骰与快照共用） */
export function focusLabel(state) {
  const f = questFocusOf(state)
  return f.type === 'side'
    ? `支线【${f.title}】${f.note ? `（${f.note}）` : ''}`
    : `主线【${f.title}】${f.stage ? `（进展：${f.stage}）` : ''}`
}

/**
 * 掷出本回合的事件骰。
 * 返回 { intensity, flavors[], sideQuest, mutation, twist, mislead, focus, spawnSide }——
 * 全部是"约束"，不是"事件内容"。其中 focus 是本回合必须服务的任务线，
 * mislead 是选项的误导度（决定要不要埋陷阱）。
 */
export function rollEventPlan(state) {
  const idx = stageIndex(state?.day)
  const intensity = pickWeighted(
    EVENT_INTENSITY,
    EVENT_INTENSITY.map((x) => x.weights[idx]),
  ).id

  // 倾向：先抽 1 个；阶段越靠后越可能叠加第二个（世界越乱，事件越"复合"）
  const pool = EVENT_FLAVORS.slice()
  const first = pool.splice(Math.floor(Math.random() * pool.length), 1)[0]
  const flavors = [first.id]
  if (Math.random() < 0.22 + idx * 0.06) {
    flavors.push(pool[Math.floor(Math.random() * pool.length)].id)
  }

  // 任务焦点：本回合事件必须围绕它生成（主线 / 某条进行中的支线）
  const focus = questFocusOf(state)

  // 支线：受"同时进行 ≤4 条、总量 ≤12 条"的引擎上限约束
  const quests = state?.sideQuests || []
  const active = quests.filter((q) => q.status === 'active').length
  const room = active < 4 && quests.length < 12
  // 主线刚刚完成并派生了新主线 → 强制从新主线抛出一条支线（任务链闭环的入口）
  const spawnSide = Boolean(state?.spinSideFromMain) && room
  const sideQuest = spawnSide || (room && Math.random() < 0.24 + idx * 0.02)

  // 变异：越往后越可能；从未变异过时略提高，让"病毒在进化"尽早立住
  const mutations = (state?.mutations || []).length
  const mutation = Math.random() < 0.05 + idx * 0.035 + (mutations === 0 ? 0.06 : 0)

  // 反转：小概率要求一个"意料之外、情理之中"的转折
  const twist = Math.random() < 0.18

  // 选项误导度：世界越乱，选项越难判断（选项不该一眼看出对错）
  const mislead = pickWeighted(
    EVENT_MISDIRECTION,
    EVENT_MISDIRECTION.map((x) => x.weights[idx]),
  ).id

  return { intensity, flavors, sideQuest, mutation, twist, mislead, focus, spawnSide }
}

/** 把事件骰渲染成提示词段落（约束骨架，不含任何事件内容） */
export function formatEventPlan(plan) {
  const it = EVENT_INTENSITY.find((x) => x.id === plan?.intensity) || EVENT_INTENSITY[1]
  const fl = (plan?.flavors || []).map((id) => EVENT_FLAVORS.find((f) => f.id === id)).filter(Boolean)
  const focus = plan?.focus || { type: 'main', title: '活下去' }
  const focusLine =
    focus.type === 'side'
      ? `· **任务焦点：支线【${focus.title}】**（${focus.note || '待推进'}） —— 本回合的事件**必须围绕这条支线展开**，实质推进它（走向完成、失败或新的障碍）。玩家上一步选择了服务于它。**支线一旦了结，焦点自动回归主线。**`
      : `· **任务焦点：主线【${focus.title}】**${focus.stage ? `（当前进展：${focus.stage}）` : ''} —— 本回合的事件**必须围绕主线展开**，推进它或让它受阻。`
  const sideLine = plan?.sideQuest
    ? plan?.spawnSide
      ? '· 支线：**本回合必须抛出一条新的支线**（sideQuestsAdd 给出 1 条）——因为**主线刚刚完成、新的主线刚刚确立**，这条支线**必须从新主线派生**（服务于新主线），由本回合的事件自然引发。'
      : '· 支线：**本回合应当抛出一条新的支线**（sideQuestsAdd 给出 1 条，且必须**从当前主线派生**、由本回合的事件自然引发）。'
    : '· 支线：本回合**不新增**支线（sideQuestsAdd 留空数组）；已有支线若推进或了结，照常写 sideQuestsUpdate。'
  const ms = EVENT_MISDIRECTION.find((x) => x.id === plan?.mislead) || EVENT_MISDIRECTION[0]
  const misleadLine = `· 选项误导度：**${ms.label}** —— ${ms.brief}`
  return [
    focusLine,
    `· 强度：**${it.label}** —— ${it.brief}`,
    `· 倾向：${fl.map((f) => `**${f.label}**（${f.desc}）`).join(' ＋ ')} —— 本回合的事件必须落在这些方向上，不要跑到别的味道去。`,
    misleadLine,
    sideLine,
    plan?.mutation
      ? '· 变异：**本回合发生一次病毒变异**（写入 mutationsAdd，并让玩家亲眼见识这个新威胁）。'
      : '· 变异：本回合**不发生**变异（mutationsAdd 留空数组）；已出现的感染体谱系仍要照常登场。',
    plan?.twist
      ? '· 反转：本回合需要**一个意料之外、情理之中的转折**——玩家以为会 A，实际发生 B，回头一看处处是伏笔。'
      : '· 反转：不强制反转，按因果自然推进即可。',
  ].join('\n')
}

/** 感染值 → 尸化分期（与病毒设定严格对应） */
export function infectionStage(v) {
  const n = Number(v) || 0
  if (n <= 0) return '未感染'
  if (n < 26) return '潜伏期'
  if (n < 56) return '发作期'
  if (n < 86) return '终末期'
  if (n < 100) return '临界尸化'
  return '已尸化'
}

/** 爆发后天数 → 文明崩塌阶段（与【崩塌时间线】严格对应） */
export function collapseStage(day) {
  const d = Number(day) || 1
  if (d <= 2) return '爆发'
  if (d <= 5) return '恐慌'
  if (d <= 10) return '失序'
  if (d <= 20) return '瓦解'
  if (d <= 40) return '残骸'
  return '长夜'
}

/* ------------------------- 昼夜（24 小时制） ------------------------- */
/**
 * 时间采用 24 小时制：state.minute 为一天内的分钟数（0-1439），state.day 为爆发后天数。
 *  · 现实 5 分钟 = 游戏 1 天 → 但时钟**只在玩家行动时推进**（挂机暂停），
 *    因此实际按"行动耗时"推进：模型给 timeCostHours（游戏小时），引擎换算成分钟累加。
 *  · 昼夜分界：白天 06:00-18:00 / 黄昏 18:00-20:00 / 夜晚 20:00-06:00。
 */

/** 一小时的分钟数 */
export const MIN_PER_HOUR = 60
/** 一天的分钟数 */
export const MIN_PER_DAY = 1440
/** 现实 5 分钟 = 游戏 1 天（仅作参考：游戏内 1 小时 ≈ 现实 12.5 秒） */
export const REAL_MS_PER_DAY = 5 * 60 * 1000

/** 黄昏开始（18:00） */
export const DUSK_FROM_MIN = 18 * 60
/** 夜晚开始（20:00） */
export const NIGHT_FROM_MIN = 20 * 60
/** 白天开始（06:00） */
export const DAY_FROM_MIN = 6 * 60

/** 归一化分钟数到 [0, 1440) */
export function normMinute(min) {
  const n = Math.round(Number(min))
  if (!Number.isFinite(n)) return 0
  return ((n % MIN_PER_DAY) + MIN_PER_DAY) % MIN_PER_DAY
}

/** 把分钟数格式化为 HH:MM */
export function formatClock(min) {
  const m = normMinute(min)
  const h = Math.floor(m / 60)
  const mm = m % 60
  return `${String(h).padStart(2, '0')}:${String(mm).padStart(2, '0')}`
}

/** 是否夜晚（20:00-06:00，影响视野、丧尸活跃度、精神消耗） */
export function isNightMinute(min) {
  const m = normMinute(min)
  return m >= NIGHT_FROM_MIN || m < DAY_FROM_MIN
}

/** 白天 / 黄昏 / 夜晚（依据 24 小时制分钟数） */
export function dayPhaseOf(min) {
  const m = normMinute(min)
  if (m >= NIGHT_FROM_MIN || m < DAY_FROM_MIN) return '夜晚'
  if (m >= DUSK_FROM_MIN) return '黄昏'
  return '白天'
}

/** 是否黄昏 */
export function isDuskMinute(min) {
  return dayPhaseOf(min) === '黄昏'
}

/** 小时的近似文字（用于叙事提示，如 03 → 凌晨三点） */
export function hourPhrase(min) {
  const h = Math.floor(normMinute(min) / 60)
  const names = ['零点', '一点', '两点', '三点', '四点', '五点', '六点', '七点', '八点', '九点', '十点', '十一点',
    '十二点', '十三点', '十四点', '十五点', '十六点', '十七点', '十八点', '十九点', '二十点', '二十一点', '二十二点', '二十三点']
  let prefix = ''
  if (h >= 0 && h < 5) prefix = '凌晨'
  else if (h < 8) prefix = '清晨'
  else if (h < 11) prefix = '上午'
  else if (h < 13) prefix = '中午'
  else if (h < 17) prefix = '下午'
  else if (h < 19) prefix = '傍晚'
  else if (h < 23) prefix = '夜里'
  else prefix = '深夜'
  return prefix + names[h]
}

/** 分钟数 → 一段自然语言时间描述（供模型理解当前时刻） */
export function timeOfDayPhrase(min) {
  const m = normMinute(min)
  const nextHour = Math.ceil(m / 60) * 60
  const untilNext = nextHour === m ? 60 : nextHour - m
  return `${formatClock(m)}（${hourPhrase(m)}，${dayPhaseOf(m)}；距下一个整点还有约 ${untilNext} 分钟）`
}

