/** 兼容：把分钟数映射为一个粗时段索引（0-5），仅在旧调用需要时用 */
export function normSlot(minuteOrSlot) {
  const m = normMinute(minuteOrSlot)
  if (m < 5 * 60) return 5 // 深夜 00:00-05:00
  if (m < 8 * 60) return 0 // 清晨
  if (m < 12 * 60) return 1 // 上午
  if (m < 17 * 60) return 2 // 午后
  if (m < 20 * 60) return 3 // 黄昏
  return 4 // 夜晚
}

