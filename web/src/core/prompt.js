/* ==================================================================
 * 事件骰（引擎掷骰 → 模型填内容）
 * ------------------------------------------------------------------
 * 「随机事件」不能交给模型"随手发挥"——那样必然趋同：不是遭遇丧尸，就是救人、找物资。
 * 所以由引擎每回合掷出一组**结构化约束**（强度 / 倾向 / 支线 / 变异 / 反转），
 * 模型必须在这个骨架里现场生成内容。这与搜刮的【产出配额】【插曲判定】是同一套设计语言：
 * **可枚举的维度归引擎，内容归模型**。约束不提供任何"事件池"，不违反"事件现场生成"的铁律。
 * ================================================================== */

/** 崩塌阶段索引（0-5）：用于按"世界恶化程度"调整随机权重 */
export function stageIndex(day) {
  const d = Number(day) || 1
  if (d <= 2) return 0
  if (d <= 5) return 1
  if (d <= 10) return 2
  if (d <= 20) return 3
  if (d <= 40) return 4
  return 5
}

/** 按权重抽取一项（weights 与 items 等长） */
function pickWeighted(items, weights) {
  const total = weights.reduce((a, b) => a + Math.max(0, Number(b) || 0), 0)
  if (total <= 0) return items[0]
  let r = Math.random() * total
  for (let i = 0; i < items.length; i++) {
    r -= Math.max(0, Number(weights[i]) || 0)
    if (r < 0) return items[i]
  }
  return items[items.length - 1]
}

