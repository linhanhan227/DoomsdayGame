/**
 * 本回合联动清单：把「必须被照看」的状态条目从快照里抽出来，放在任务说明最显眼的位置。
 * 目的：模型容易忽略埋在长快照里的 conditions / flags / 支线，这里强制它逐项过一遍。
 */
export function buildLinkageChecklist(state) {
  const inv = (state.inventory || []).map((i) => {
    const tags = []
    if (i.category) tags.push(i.category)
    if (i.fits) tags.push(`适用${i.fits}`)
    if (i.tradable) tags.push('可交换')
    return `${i.name}${i.qty > 1 ? `×${i.qty}` : ''}${tags.length ? `（${tags.join('·')}）` : ''}`
  })
  const quests = (state.sideQuests || []).filter((q) => q.status === 'active')
  const conditions = state.conditions || []
  const flags = state.flags || []
  const mq = state.mainQuest
  return [
    `· **本回合任务焦点**：${focusLabel(state)} —— 本回合的事件必须围绕它生成。`,
    `· **背包**（${inv.length} 件）：${inv.length ? inv.join('、') : '空——"一无所有"本身就该是本回合的压力'}`,
    `· **主线**（第 ${state.mainQuestSeq || 1} 条）：${
      mq
        ? `【${mq.title}】进展：${mq.stage || '尚未推进'}${mq.note ? `｜线索：${mq.note}` : ''}`
        : '（尚未确立——本回合应当让主角的目标清晰起来）'
    }`,
    `· **进行中的支线**（${quests.length} 条）：${
      quests.length ? quests.map((q) => `${q.title}（${q.note || '待推进'}）`).join('；') : '（无）'
    }`,
    `· **身体状况**（${conditions.length} 项）：${conditions.length ? conditions.join('、') : '（无伤病）'}`,
    `· **剧情标记**（${flags.length} 条）：${flags.length ? flags.join('、') : '（无）'}`,
  ].join('\n')
}

